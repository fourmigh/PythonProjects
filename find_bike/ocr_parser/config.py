# ============================================================
LICENSE_PATTERNS: List[str] = [
    # 模式1：明确的“车牌号: xxx”或“牌照: xxx”格式
    r'车牌号[：:]\s*([A-Z0-9]{3,8})',
    r'牌照[：:]\s*([A-Z0-9]{3,8})',
    r'号码[：:]\s*([A-Z0-9]{3,8})',
    
    # 模式2：明确提到“车牌”后的数字字母组合
    r'车牌\s*([A-Z0-9]{3,8})',
    r'牌照\s*([A-Z0-9]{3,8})',
    
    # 模式3：标准 NNN AAA 或 AAA NNN 格式
    r'(\d{3})\s+([A-Z]{3})',
    r'([A-Z]{3})\s+(\d{3})',
    r'(\d{3}[A-Z]{3})',
    
    # 模式4：松散匹配（数字+空格+字母，或字母+空格+数字）
    r'(\d{3,4})\s+([A-Z]{2,4})',
    r'([A-Z]{2,4})\s+(\d{3,4})',
    
    # 模式5：纯字母数字组合，5-8位，且必须包含字母和数字
    r'\b(?=[A-Z]*\d+[A-Z]*\d*)[A-Z0-9]{5,8}\b'
]

